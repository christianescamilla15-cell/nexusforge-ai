# ── registry ────────────────────────────────────────────────────────


# Keyed by template_id. Each value is (summary, render_fn).
_REGISTRY: dict[str, tuple[TemplateSummary, Callable[[PlatformSpec], dict[str, str]]]] = {
    "fastapi_react_postgres": (
        _fastapi_react_postgres_summary(),
        _render_fastapi_react_postgres,
    ),
}


def list_templates() -> list[TemplateSummary]:
    """Return all registered template summaries."""
    return [summary for summary, _ in _REGISTRY.values()]


def get_template(template_id: str) -> tuple[TemplateSummary, Callable[[PlatformSpec], dict[str, str]]]:
    """Look up a template by id. Raises KeyError if not found."""
    return _REGISTRY[template_id]


def rank_for_spec(spec: PlatformSpec) -> list[TemplateMatch]:
    """Score every template against the spec and return them sorted
    by score descending. Templates with score == 0 are still
    included so the frontend can show "incompatible" state."""
    matches: list[TemplateMatch] = []
    for summary, _render in _REGISTRY.values():
        score, signals = _score_against(summary, spec)
        matches.append(TemplateMatch(template=summary, score=score, matched_signals=signals))
    matches.sort(key=lambda m: m.score, reverse=True)
    return matches
