"""Template registry for the Platform Synthesizer.

A template is a curated, tested project skeleton with a known
stack. It declares which `PlatformSpec` slots it can absorb, what
its required slots are, and its scoring signals (which spec values
make it a good match).

The first iteration ships ONE template: FastAPI + React + Postgres.
That's the stack Christian uses himself, the most-tested combo in
NexusForge, and the easiest to verify end-to-end. Adding more
templates is purely additive — register a new one in `_REGISTRY`
and add a `_render_*` function below.

Each template's `_render` function is responsible for:
  1. Emitting the file tree as a dict {relative_path: content_str}
  2. Substituting spec slot values into the file contents
  3. Validating that all required slots are filled before render

The synthesizer module writes the dict to disk.
"""
from __future__ import annotations

from typing import Callable

from .schemas import PlatformSpec, TemplateMatch, TemplateSummary


# ── scoring helpers ─────────────────────────────────────────────────


def _score_against(template: TemplateSummary, spec: PlatformSpec) -> tuple[float, list[str]]:
    """Score a template against the user's accumulated spec.

    Returns (score in [0,1], list of matched-signal strings for
    the debug panel). Each signal that lines up adds a fixed
    weight; the final score is normalized.
    """
    signals: list[str] = []
    score = 0.0

    # If the user picked an explicit language, the template MUST
    # match or it scores zero. Same for backend framework.
    if spec.language and spec.language not in {s.lower() for s in template.stack}:
        return 0.0, [f"language mismatch: spec={spec.language}, template={template.stack}"]

    # Stack overlaps: strong signal.
    template_stack_lower = {s.lower() for s in template.stack}
    if spec.backend_framework and spec.backend_framework.lower() in template_stack_lower:
        score += 0.30
        signals.append(f"backend framework matches: {spec.backend_framework}")
    if spec.frontend_framework and spec.frontend_framework.lower() in template_stack_lower:
        score += 0.20
        signals.append(f"frontend framework matches: {spec.frontend_framework}")
    if spec.database and spec.database.lower() in template_stack_lower:
        score += 0.15
        signals.append(f"database matches: {spec.database}")

    # `best_for` matches: each phrase in best_for that appears in
    # the user's description or features adds 0.10.
    haystack = " ".join(
        [
            (spec.description or "").lower(),
            *[f.lower() for f in spec.features],
            *[i.lower() for i in spec.integrations],
        ]
    )
    for phrase in template.best_for:
        if phrase.lower() in haystack:
            score += 0.10
            signals.append(f"use-case match: {phrase!r}")

    # If the user has any spec at all (description filled), give
    # the default template (FastAPI+React+Postgres) a small floor
    # score so it's always at least visible as a fallback.
    if template.template_id == "fastapi_react_postgres" and (
        spec.description or spec.project_name or spec.language is None
    ):
        score = max(score, 0.20)
        if not signals:
            signals.append("default fallback (always visible)")

    # Cap at 1.0.
    return min(score, 1.0), signals


